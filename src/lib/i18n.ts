export function translateWorkflowText(text: string | null | undefined, locale: Locale) {
  if (!text || locale === "th") {
    return text;
  }

  const purchaseOrders = text.match(/^แปลง PR เป็น PO: (.+)$/);
  if (purchaseOrders) return `Converted PR to POs: ${purchaseOrders[1]}`;

  const agedClosure = text.match(/^(ปิดงานเนื่องจากสั่งซื้อเกิน 1 เดือน โดย(?:ปิดยอดค้างรับที่เหลือทั้งหมด|ไม่มียอดค้างรับเหลือ))( \| [\s\S]+)?$/);
  if (agedClosure) return `${translatedWorkflowText[agedClosure[1]]}${agedClosure[2] ?? ""}`;

  const orderClosure = text.match(/^(ปิดงาน โดย(?:ปิดยอดค้างรับที่เหลือทั้งหมด|ไม่มียอดค้างรับเหลือ))( \| [\s\S]+)?$/);
  if (orderClosure) return `${translatedWorkflowText[orderClosure[1]]}${orderClosure[2] ?? ""}`;

  const cancellationReference = text.match(
    /^([\s\S]+) \| เลขอ้างอิงการยกเลิก PO: (.+)$/,
  );

  if (cancellationReference) {
    return `${cancellationReference[1]} | PO cancellation reference: ${cancellationReference[2]}`;
  }

  return translatedWorkflowText[text] ?? text;
}

export function translateNotificationTitle(title: string, locale: Locale) {
  if (locale === "th") {
    return title;
  }

  return translatedNotificationTitles[title] ?? title;
}

export function translateNotificationMessage(message: string, locale: Locale) {
  if (locale === "th") {
    return message;
  }

  for (const translator of translatedNotificationMessages) {
    const match = message.match(translator.pattern);

    if (match) {
      return translator.render(match);
    }
  }

  return message;
}
